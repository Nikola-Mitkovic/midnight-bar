const assert=require('node:assert/strict'),fs=require('node:fs');
const g=require('./deck.js');
const recipes=JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../recipes.json'),'utf8'));
const deck=g.createDeck(recipes);
assert.equal(deck.length,52);assert.equal(new Set(deck.map(c=>c.cocktailId)).size,52);
assert(!deck.some(c=>c.suit==='★'));
assert.throws(()=>g.createDeck(recipes.slice(1)));
assert.throws(()=>g.createDeck([...recipes,recipes[0]]));
const saved=JSON.stringify(deck), shuffled=g.shuffle(deck,()=>0.5);
assert.equal(JSON.stringify(deck),saved);assert.notDeepEqual(shuffled,deck);
assert.deepEqual(shuffled.map(c=>c.cocktailId).sort(),deck.map(c=>c.cocktailId).sort());
assert.throws(()=>g.shuffle(deck,()=>1));
const d=g.deal(deck,4,5);
assert.equal(d.remaining.length,32);assert.equal(d.hands[1][1].cocktailId,deck[5].cocktailId);
assert.equal(new Set([...d.hands.flat(),...d.remaining].map(c=>c.cocktailId)).size,52);
assert.throws(()=>g.deal(deck,11,5));assert.throws(()=>g.deal(deck,0,5));
const h=s=>s.split(' ').map(c=>({rank:c.slice(0,-1),suit:c.slice(-1)}));
const cases=[['A♠ J♥ 9♣ 7♦ 3♠',0],['A♠ A♥ 9♣ 7♦ 3♠',1],['A♠ A♥ 9♣ 9♦ 3♠',2],['A♠ A♥ A♣ 9♦ 3♠',3],['A♠ 2♥ 3♣ 4♦ 5♠',4],['A♠ J♠ 9♠ 7♠ 3♠',5],['A♠ A♥ A♣ 9♦ 9♠',6],['A♠ A♥ A♣ A♦ 9♠',7],['5♠ 6♠ 7♠ 8♠ 9♠',8],['10♠ J♠ Q♠ K♠ A♠',8]];
for(const [hand,expected] of cases)assert.equal(g.evaluatePoker(h(hand)).category,expected,hand);
assert.equal(g.evaluatePoker(h(cases[9][0])).name,'Royal flush');
for(let i=1;i<cases.length;i++)assert.equal(g.comparePoker(h(cases[i][0]),h(cases[i-1][0])),1);
assert.equal(g.comparePoker(h('A♠ 2♥ 3♣ 4♦ 5♠'),h('2♠ 3♥ 4♣ 5♦ 6♠')),-1);
assert.equal(g.comparePoker(h('A♠ A♥ 9♣ 7♦ 4♠'),h('A♣ A♦ 9♥ 7♠ 3♥')),1);
assert.equal(g.comparePoker(h('A♠ K♥ 9♣ 7♦ 4♠'),h('A♣ K♦ 9♥ 7♠ 4♥')),0);
assert.equal(g.evaluatePoker(h('Q♠ K♥ A♣ 2♦ 3♠')).category,0);
assert.throws(()=>g.evaluatePoker(h('A♠ A♠ 9♣ 7♦ 4♠')));assert.throws(()=>g.evaluatePoker(h('A♠ K♥')));
assert.deepEqual(g.scoreBlackjack(h('A♠ K♥')),{total:21,soft:true,bust:false,blackjack:true});
assert.deepEqual(g.scoreBlackjack(h('A♠ A♥ 9♣')),{total:21,soft:true,bust:false,blackjack:false});
assert.deepEqual(g.scoreBlackjack(h('A♠ A♥ K♣')),{total:12,soft:false,bust:false,blackjack:false});
assert.equal(g.scoreBlackjack(h('K♠ Q♥ 2♣')).bust,true);
assert.equal(g.scoreBlackjack(h('7♠ 7♥ 7♣')).blackjack,false);
assert.equal(JSON.stringify(deck),saved);
console.log('PASS: standard deck mapping, non-mutating shuffle/deal, capacity and duplicate validation; every poker category, wheel, tie and kicker; blackjack ace adjustment, naturals and busts.');
